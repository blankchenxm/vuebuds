/*
 * HM01B0 register tables.
 *
 * Values are the VueBuds hm01b0_init_optimized_vlm() sequence, split by purpose
 * like the ESP32 driver. hm01b0_init() applies them in the original order:
 * base -> test pattern -> mode -> common -> interface.
 */
#include <stdint.h>

#include "private_include/hm01b0_regs.h"
#include "private_include/hm01b0_tables.h"

#define HM01B0_TABLE_COUNT(table) (sizeof(table) / sizeof((table)[0]))

#define HM01B0_REG_WRITE(reg, val) \
  { .addr = (reg), .value = (val), .mask = UINT8_MAX, .delay_ms = 0 }

/* Clock source and pad drive, written right after entering standby. */
const hm01b0_regval_t hm01b0_base_init[] = {
  HM01B0_REG_WRITE(HM01B0_REG_ANA_REGISTER_17, HM01B0_CLOCK_SOURCE_EXTERNAL_MCLK),
  HM01B0_REG_WRITE(HM01B0_REG_IO_DRIVE_STRENGTH, 0xFF),
};
const size_t hm01b0_base_init_count = HM01B0_TABLE_COUNT(hm01b0_base_init);

