/*
 * 1-bit serial output on D0, MSB first, PCLKO gated by line (datasheet table 6.5),
 * so PCLKO only toggles while a line is valid, like the HM01B0 setup.
 * Sensor_Core = MCLK / 8 = 1 MHz; serial PCLKO = 8 x Sensor_Core = 8 MHz (SPIS limit).
 */
const hm0360_regval_t hm0360_interface_1bit[] = {
  HM0360_REG_WRITE(HM0360_REG_PLL1_CONFIG, HM0360_PLL1_I2C_DIV2 | HM0360_PLL1_PCLKO_DIV1 | HM0360_PLL1_CORE_DIV8),
  HM0360_REG_UPDATE(HM0360_REG_ANA_REGISTER_04, HM0360_SERIAL_WIDTH_MASK, HM0360_SERIAL_1BIT),
  HM0360_REG_UPDATE(HM0360_REG_OPFM_CTRL, HM0360_OPFM_PCLKO_GATED, HM0360_OPFM_PCLKO_GATED),
  // Table 6.5 "1-bit, gated by line, MSB": 0x309E = 2 exactly (OpenMV's table leaves 0x05).
  HM0360_REG_WRITE(HM0360_REG_PCLKO_GATED_EN, HM0360_PCLKO_GATED_BY_LINE),
  // No extra PCLKO clocks around each line: OpenMV's 8 front / 32 end porch clocks would add
  // 40 bytes to every 160-byte line.
  HM0360_REG_WRITE(HM0360_REG_PCLKO_LINE_FRONT_H, 0x00),
  HM0360_REG_WRITE(HM0360_REG_PCLKO_LINE_FRONT_L, 0x00),
  HM0360_REG_WRITE(HM0360_REG_PCLKO_LINE_END_H, 0x00),
  HM0360_REG_WRITE(HM0360_REG_PCLKO_LINE_END_L, 0x00),
  // OpenMV's table writes 0x30A5 = 0x04: PCLKO continuous mode, which keeps PCLKO running
  // through blanking (SPIS then receives the whole 376-clock line), and VSYNC mode off.
  // Restore the datasheet default: VSYNC mode only (0x00 leaves the outputs Hi-Z, table 6.4).
  HM0360_REG_WRITE(HM0360_REG_OUTPUT_EN, HM0360_OUTPUT_EN_VSYNC_MODE),
  HM0360_REG_WRITE(HM0360_REG_ANA_REGISTER_07, HM0360_MSB_FIRST | HM0360_PCLKO_POLARITY),
  HM0360_REG_WRITE(HM0360_REG_COMMAND_UPDATE, HM0360_COMMAND_UPDATE_APPLY),
};
const size_t hm0360_interface_1bit_count = HM0360_TABLE_COUNT(hm0360_interface_1bit);
